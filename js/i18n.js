let LANG = 'en';
try { LANG = localStorage.getItem('avct_lang') || 'en'; } catch (e) { LANG = 'en'; }
if (I18N[LANG] === undefined) LANG = 'en';

function t(key) {
  const dict = I18N[LANG] || I18N.en;
  if (dict[key] !== undefined) return dict[key];
  if (I18N.en[key] !== undefined) return I18N.en[key];
  return key;
}

function setLang(code) {
  if (!I18N[code]) return;
  LANG = code;
  try { localStorage.setItem('avct_lang', code); } catch (e) {}
  document.documentElement.lang = code;
  document.documentElement.dir = code === 'ar' ? 'rtl' : 'ltr';
  const lb = document.getElementById('langBtn');
  if (lb) lb.querySelector('span').textContent = code === 'ar' ? 'EN' : 'AR';
  refreshTodayChip();
  if (typeof afterLanguageChange === 'function') afterLanguageChange();
}

/* ---------- Date helpers (localized, timezone-safe) ---------- */
function pad2(n) { return n < 10 ? '0' + n : '' + n; }

function fmtDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso + (iso.length === 10 ? 'T00:00:00' : ''));
  if (isNaN(d)) return iso;
  return d.toLocaleDateString(LANG === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', { day: 'numeric', month: 'short' });
}
function fmtDateLong(iso) {
  if (!iso) return '—';
  const d = new Date(iso + (iso.length === 10 ? 'T00:00:00' : ''));
  if (isNaN(d)) return iso;
  return d.toLocaleDateString(LANG === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', { weekday: 'short', day: 'numeric', month: 'short', year: 'numeric' });
}
/* local calendar date (YYYY-MM-DD) — no timezone shifting */
function todayISO() {
  const n = new Date();
  return n.getFullYear() + '-' + pad2(n.getMonth() + 1) + '-' + pad2(n.getDate());
}
/* timezone-safe day arithmetic on YYYY-MM-DD strings */
function addDays(iso, n) {
  const p = String(iso || '').split('-').map(Number);
  if (p.length !== 3 || p.some(isNaN)) return todayISO();
  const dt = new Date(Date.UTC(p[0], p[1] - 1, p[2] + n));
  return dt.toISOString().slice(0, 10);
}
/* calendar day difference (a - b) in days */
function diffDays(aISO, bISO) {
  const pa = String(aISO).split('-').map(Number);
  const pb = String(bISO).split('-').map(Number);
  if (pa.length !== 3 || pb.length !== 3) return Infinity;
  return Math.round((Date.UTC(pa[0], pa[1] - 1, pa[2]) - Date.UTC(pb[0], pb[1] - 1, pb[2])) / 86400000);
}
